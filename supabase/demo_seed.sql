-- ============================================================
-- Auth users: 5명의 데모 봇 (FK 충족용 — 비밀번호는 임의, 로그인 불가하게)
-- ============================================================

-- 트리거(handle_new_user)가 자동으로 profiles row를 만듭니다. 하지만 nickname unique 충돌이 있을 수 있으니
-- 이미 존재하면 skip.

do $$
declare
  bot record;
begin
  for bot in
    select * from (values
      ('11111111-1111-1111-1111-111111111101'::uuid, '이끼',     '습기 많은 골목과 오래된 간판을 모읍니다.', '비 오기 직전의 색',  array['장마','돌담','간판']),
      ('11111111-1111-1111-1111-111111111102'::uuid, '소금',     '부엌 창가, 햇볕 자국, 그릇의 그림자.',       '오후 세 시의 식탁',  array['주방','오후','그림자']),
      ('11111111-1111-1111-1111-111111111103'::uuid, '리넨',     '필름 카메라 두 대로 천천히.',                 '느린 산책',          array['필름','동네','천천히']),
      ('11111111-1111-1111-1111-111111111104'::uuid, '느와르',   '밤. 가로등. 그리고 비.',                       '검은 빛',            array['야경','도시','비']),
      ('11111111-1111-1111-1111-111111111105'::uuid, '주전자',   '카페에서 컵 위로 떨어지는 빛만 본다.',         '하루의 윗면',        array['카페','반사','커피'])
    ) as t(id, nickname, bio, exhibition_title, words)
  loop
    -- 1) auth.users 직접 insert (트리거가 profiles 생성)
    insert into auth.users (id, instance_id, aud, role, email, encrypted_password, email_confirmed_at, raw_user_meta_data, created_at, updated_at)
    values (
      bot.id,
      '00000000-0000-0000-0000-000000000000'::uuid,
      'authenticated',
      'authenticated',
      'demo+' || bot.nickname || '@siseonjip.demo',
      '$2a$10$disabled.placeholder.cannot.login...........',
      now(),
      jsonb_build_object('nickname', bot.nickname, 'is_bot', true),
      now(),
      now()
    )
    on conflict (id) do nothing;

    -- 2) profile 보강 (트리거는 nickname만 채움)
    update profiles
    set bio = bot.bio,
        exhibition_title = bot.exhibition_title,
        words = bot.words
    where id = bot.id;
  end loop;
end $$;

